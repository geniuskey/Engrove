const dictionaries = { en, ko } as const;

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
}

function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>) {
  let result: string = dictionaries[locale][key] ?? en[key];
  for (const [name, value] of Object.entries(values ?? {})) {
    result = result.replaceAll(`{${name}}`, String(value));
  }
  return result;
}

const I18nContext = createContext<I18nValue>({
  locale: 'en',
  setLocale: () => undefined,
  t: (key, values) => translate('en', key, values),
});

export function I18nProvider({ children }: PropsWithChildren) {
  const [locale, setLocale] = useState<Locale>(() =>
    window.localStorage.getItem('engrove-locale') === 'ko' ? 'ko' : 'en',
  );

  useEffect(() => {
    window.localStorage.setItem('engrove-locale', locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nValue>(
    () => ({ locale, setLocale, t: (key, values) => translate(locale, key, values) }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
